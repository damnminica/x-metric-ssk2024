function pearson(pairs) {
	const n = pairs.length;
	if (n < 3) return null;
	let sx = 0;
	let sy = 0;
	for (const p of pairs) {
		sx += p.x;
		sy += p.y;
	}
	const mx = sx / n;
	const my = sy / n;
	let num = 0;
	let dx = 0;
	let dy = 0;
	for (const p of pairs) {
		const a = p.x - mx;
		const b = p.y - my;
		num += a * b;
		dx += a * a;
		dy += b * b;
	}
	if (dx === 0 || dy === 0) return null;
	return num / Math.sqrt(dx * dy);
}
/** Ordinary least squares: y = a + b x. */
function ols(pairs) {
	const n = pairs.length;
	if (n < 2) return null;
	let sx = 0;
	let sy = 0;
	let sxx = 0;
	let sxy = 0;
	for (const p of pairs) {
		sx += p.x;
		sy += p.y;
		sxx += p.x * p.x;
		sxy += p.x * p.y;
	}
	const den = n * sxx - sx * sx;
	if (den === 0) return null;
	const b = (n * sxy - sx * sy) / den;
	return {
		a: (sy - b * sx) / n,
		b
	};
}
